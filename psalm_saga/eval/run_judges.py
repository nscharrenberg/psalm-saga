"""Model judges that run inside a single run's evaluation (stage `evaluate`, `judges: true`).

Two questions the automatic measures answer only indirectly:

  content  Does the synthetic text tell the same story? The judge reads the chapter summaries of the
           source and of the synthetic text, both produced by the same analysis (extract / recover),
           side by side — never the two books — so it scales to novels and sees no source wording
           beyond the analysis' own paraphrase. Rated 1–5 overall and per chapter.
  style    Is it written the same way? The judge reads three excerpts of each text from the same
           relative positions, names masked, and rates voice, register, rhythm and imagery 1–5.

Both are policy-aware: under `regenerate` there is no target and the judge does not run; under
`abstract` the judge is told that particulars are supposed to differ. Ratings become scores with
score = (rating − 1) / 4. They use the model role `judge` (set `models.judge` to a model that did not
write the text, to avoid self-preference).
"""

from __future__ import annotations

import re
from typing import Literal

from pydantic import BaseModel, Field

from psalm_saga.artifacts import Bible
from psalm_saga.llm import Part

SYSTEM = ("You are an expert literary scholar acting as a careful, blind evaluator in a research study. "
          "Judge only what you are asked, on the evidence given.")


class ChapterRating(BaseModel):
    chapter: int
    rating: int = Field(ge=1, le=5)
    missing: str = Field("", description="What of the source chapter's story is absent or contradicted, briefly.")


class ContentVerdict(BaseModel):
    rating: int = Field(ge=1, le=5, description="1 = a different story, 3 = the same outline with clear losses or "
                        "changes, 5 = the same story: same events, order, outcomes and who does what.")
    chapters: list[ChapterRating] = Field(default_factory=list)
    reason: str = ""


class StyleVerdict(BaseModel):
    rating: int = Field(ge=1, le=5, description="1 = clearly different writing, 3 = related but distinguishable, "
                        "5 = indistinguishable in voice, register, rhythm and imagery.")
    reason: str = ""


def _summaries(bible: Bible) -> str:
    out = []
    for ch in bible.chapters:
        events = "; ".join(e.description for e in ch.events[:12])
        out.append(f"Chapter {ch.index}: {ch.summary}" + (f"\n  Events: {events}" if events else ""))
    return "\n".join(out)


async def content_judge(ctx, source_bible: Bible, synthetic_bible: Bible, renames: dict[str, str],
                        policy: dict[str, str]) -> dict:
    pol = {k: policy.get(k, "preserve") for k in ("plot_structure", "scene_sequence")}
    if "regenerate" in pol.values():
        return {"score": None, "reason_missing": "not applicable: the plot was regenerated by policy, so there is no "
                                                 "story to match"}
    level = ("the concrete story: the same events in the same order, the same outcomes, the same people doing the same things"
             if all(v == "preserve" for v in pol.values()) else
             "function and structure: the same kinds of events in the same order with the same consequences; concrete "
             "particulars (names, places, objects, specific details) are SUPPOSED to differ")
    pairs = "; ".join(f"{a} → {b}" for a, b in list(renames.items())[:60]) or "(none)"
    prompt = (f"Two analysts summarised two texts chapter by chapter with the same procedure. Text B is meant to tell "
              f"the story of text A again, with new names. Compare at the level of {level}. Names were changed on "
              f"purpose (renames: {pairs}); ignore wording.\n\nRate overall and per chapter of A how far B tells the same "
              f"story (1–5), and say briefly what is missing or contradicted.\n\n# Text A (source)\n{_summaries(source_bible)}"
              f"\n\n# Text B (synthetic)\n{_summaries(synthetic_bible)}")
    v = await ctx.json("judge", SYSTEM, [Part(prompt)], ContentVerdict, temperature=0.0,
                       hints={"chapters": len(source_bible.chapters)}, tag="judge:content")
    return {"rating": v.rating, "score": round((v.rating - 1) / 4, 3), "reason": v.reason, "level": level,
            "chapters": [c.model_dump() for c in v.chapters]}


def _mask(text: str, names: list[str]) -> str:
    for n in sorted({n for n in names if len(n) > 2}, key=len, reverse=True):
        text = re.sub(rf"(?<!\w){re.escape(n)}(?!\w)", "[NAME]", text)
    return text


def _excerpts(text: str, words: int = 350, positions=(0.15, 0.5, 0.85)) -> list[str]:
    toks = text.split()
    if len(toks) <= words * len(positions):
        return [" ".join(toks)]
    out = []
    for p in positions:
        start = max(0, min(len(toks) - words, int(p * len(toks)) - words // 2))
        out.append(" ".join(toks[start:start + words]))
    return out


async def style_judge(ctx, source: str, story: str, names: list[str], policy: dict[str, str]) -> dict:
    pol = policy.get("writing_style", "preserve")
    if pol == "regenerate":
        return {"score": None, "reason_missing": "not applicable: the writing style was regenerated by policy"}
    a = "\n\n[…]\n\n".join(_mask(x, names) for x in _excerpts(source))
    b = "\n\n[…]\n\n".join(_mask(x, names) for x in _excerpts(story))
    level = ("the same author's hand" if pol == "preserve" else
             "the same kind of writing (register, rhythm, narration), though not necessarily the same hand")
    prompt = (f"Below are excerpts from two texts, names masked. They tell different or reworded content on purpose; "
              f"ignore what happens and judge only how it is written: voice, register and vocabulary, sentence rhythm, "
              f"paragraphing, use of dialogue, imagery. Rate 1–5 how far text B reads like {level} of text A.\n\n"
              f"# Text A\n{a}\n\n# Text B\n{b}")
    v = await ctx.json("judge", SYSTEM, [Part(prompt)], StyleVerdict, temperature=0.0, hints={}, tag="judge:style")
    return {"rating": v.rating, "score": round((v.rating - 1) / 4, 3), "reason": v.reason, "level": level}


# ------------------------------------------------------------------ PSALM dimension judge
# An improved version of the PSALM evaluation (Scharrenberg & Sun, 2026): the two texts are compared
# along the six PSALM dimensions and their 36 sub-dimensions. For every sub-dimension the judge must
# first describe how each text realises it, cite short evidence from both, and then argue its verdict
# — separately for FUNCTION (does B do the same thing: role, effect, structure?) and EXPRESSION (are the
# concrete particulars and their realisation the same?). The split follows the idea–expression
# distinction: under EU law a work is protected as its author's own intellectual creation, in its
# expression, not in its ideas or functions. Function similarity is what a faithful synthetic text
# should have; expression similarity where the policy asks for change is an appropriation risk.

LEVELS = ("1 = unrelated; 2 = loosely related; 3 = clearly related but with substantial differences; "
          "4 = largely the same with minor differences; 5 = the same")


class SubVerdict(BaseModel):
    key: str = Field(description="Sub-dimension key, as listed.")
    in_a: str = Field(description="How text A realises this aspect, in your own words (1–2 sentences).")
    in_b: str = Field(description="How text B realises it (1–2 sentences).")
    evidence_a: str = Field("", description="A short quotation (at most 15 words) from A that shows it.")
    evidence_b: str = Field("", description="A short quotation (at most 15 words) from B that shows it.")
    reasoning: str = Field(description="The argument from the evidence to both verdicts, 1–3 sentences.")
    function_similarity: int = Field(ge=1, le=5, description="Does B do the same thing here — same role, effect, "
                                     "mechanism, structure — regardless of the particulars? " + LEVELS)
    expression_similarity: int = Field(ge=1, le=5, description="Are the concrete particulars and their realisation "
                                       "the same (specific traits, events, images, places, phrasing)? Changed names "
                                       "alone do not make expression different. " + LEVELS)
    confidence: Literal["low", "medium", "high"] = "medium"


class DimensionVerdict(BaseModel):
    dimension: str
    subdimensions: list[SubVerdict]
    summary: str = Field("", description="One or two sentences on the dimension as a whole.")


def _windows(text: str, k: int, words: int) -> list[str]:
    toks = text.split()
    if len(toks) <= words * k:
        return [" ".join(toks)]
    out = []
    for i in range(k):
        pos = (i + 0.5) / k
        start = max(0, min(len(toks) - words, int(pos * len(toks)) - words // 2))
        out.append(" ".join(toks[start:start + words]))
    return out


async def psalm_judge(ctx, taxonomy, source: str, story: str, source_bible: Bible | None, story_bible: Bible | None,
                      policy: dict[str, str], cfg) -> dict:
    """One call per dimension (in parallel). Returns per-dimension scores, the per-sub-dimension
    argumentation, and two aggregates: `fidelity` (mean function similarity over dimensions the policy
    does not regenerate) and `appropriation` (mean expression similarity over the surface aspects of
    dimensions the policy abstracts or regenerates; None when everything is preserved)."""
    import asyncio

    full = len(source.split()) <= cfg.full_text_words and len(story.split()) <= cfg.full_text_words
    if full:
        material = f"# Text A (source)\n{source}\n\n# Text B (synthetic)\n{story}"
        mode = "full texts"
    else:
        wa, wb = _windows(source, cfg.excerpts, cfg.excerpt_words), _windows(story, cfg.excerpts, cfg.excerpt_words)
        pairs = "\n\n".join(f"## Excerpt {i + 1} of A (at the same relative position)\n{a}\n\n## Excerpt {i + 1} of B\n{b}"
                            for i, (a, b) in enumerate(zip(wa, wb, strict=False)))
        summ = ""
        if source_bible and story_bible:
            summ = f"\n\n# Chapter summaries of A (by an analyst)\n{_summaries(source_bible)}\n\n# Chapter summaries of B\n{_summaries(story_bible)}"
        material = f"{pairs}{summ}"
        mode = f"{len(wa)} aligned excerpts of ~{cfg.excerpt_words} words each, plus chapter summaries"

    async def one(dim) -> dict:
        pol = policy.get(dim.key, "preserve")
        intent = {"preserve": "B is meant to keep this dimension as in A (only names changed).",
                  "abstract": "B is meant to keep the FUNCTION of this dimension but re-invent its concrete particulars.",
                  "regenerate": "B is meant to replace this dimension freely; neither similarity is expected."}[pol]
        subs = "\n".join(f"- {s.key} ({s.label}){' [surface: its concrete realisation is the most identifying part]' if s.surface else ''}: {s.guidance}"
                         for s in dim.subdimensions)
        prompt = (f"Compare two literary texts on the dimension **{dim.label}** — {dim.description}\n\n"
                  f"Text B is a rewritten counterpart of text A with new names. Policy for this dimension: {intent} "
                  "Judge what is there, not what was intended.\n\n"
                  f"For EACH sub-dimension below: describe how A and how B realise it, quote short evidence from both "
                  f"(at most 15 words each; leave empty if the aspect is not exercised), argue from that evidence, then "
                  f"rate function similarity and expression similarity separately (1–5), and state your confidence. "
                  f"Function is what the aspect does (role, effect, mechanism, structure); expression is its concrete "
                  f"realisation (specific traits, events, images, settings, phrasing). Names differ by design and do not "
                  f"count. If a short text barely exercises an aspect, say so and use low confidence.\n\n"
                  f"Sub-dimensions:\n{subs}\n\nMaterial ({mode}):\n\n{material}")
        v = await ctx.json("judge", SYSTEM, [Part(prompt)], DimensionVerdict, temperature=0.0,
                           hints={"subdimensions": len(dim.subdimensions)}, tag=f"judge:psalm:{dim.key}")
        by = {s.key: s for s in dim.subdimensions}
        rows = [sv for sv in v.subdimensions if sv.key in by] or v.subdimensions
        f = [(sv.function_similarity - 1) / 4 for sv in rows]
        e = [(sv.expression_similarity - 1) / 4 for sv in rows]
        surf = [(sv.expression_similarity - 1) / 4 for sv in rows if by.get(sv.key) and by[sv.key].surface]
        return {"dimension": dim.key, "label": dim.label, "policy": pol, "summary": v.summary,
                "function": round(sum(f) / len(f), 3) if f else None, "expression": round(sum(e) / len(e), 3) if e else None,
                "surface_expression": round(sum(surf) / len(surf), 3) if surf else None,
                "subdimensions": [{**sv.model_dump(), "label": by[sv.key].label if sv.key in by else sv.key,
                                   "surface": bool(by.get(sv.key) and by[sv.key].surface)} for sv in rows]}

    dims = await asyncio.gather(*(one(d) for d in taxonomy.dimensions))
    fid = [d["function"] for d in dims if d["function"] is not None and d["policy"] != "regenerate"]
    app = [d["surface_expression"] if d["surface_expression"] is not None else d["expression"]
           for d in dims if d["policy"] in ("abstract", "regenerate") and d["expression"] is not None]
    return {"mode": mode, "dimensions": dims,
            "fidelity": round(sum(fid) / len(fid), 3) if fid else None,
            "appropriation": round(sum(app) / len(app), 3) if app else None,
            "reason_missing_appropriation": None if app else
            "every dimension is preserved, so similar concrete expression is intended; see the per-dimension table"}
